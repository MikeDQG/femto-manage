import { test, expect } from '@playwright/test'

test('manual activity validates, warns on overlap, saves once and cancels', async ({ page }) => {
  const email = `journal-${crypto.randomUUID()}@example.com`
  const csrf = await (await page.request.get('/api/auth/csrf')).json()
  expect((await page.request.post('/api/auth/register', {
    headers: { [csrf.headerName]: csrf.token }, data: { email, password: 'long-password-123' },
  })).status()).toBe(201)
  await page.goto('/')
  await page.getByLabel('E-pošta').fill(email)
  await page.getByLabel('Geslo', { exact: true }).fill('long-password-123')
  await page.getByRole('button', { name: 'Prijava' }).click()
  await page.getByRole('button', { name: 'Koledar' }).click()
  await page.getByRole('button', { name: /Dodaj aktivnost/ }).click()
  await page.getByRole('button', { name: 'Potrdi aktivnost' }).click()
  await expect(page.getByText('Naziv je obvezen.')).toBeVisible()
  await page.getByLabel('Naziv').fill('Branje')
  const day = new Date().toLocaleDateString('en-CA')
  await page.getByLabel('Začetek').fill(`${day}T09:00`)
  await page.getByLabel('Konec').fill(`${day}T10:00`)
  await page.getByLabel('Kategorija').selectOption({ label: 'Delo' })
  await page.getByRole('button', { name: 'Prekliči' }).click()
  await expect(page.getByText('Branje')).toHaveCount(0)
  await page.getByRole('button', { name: /Dodaj aktivnost/ }).click()
  await page.getByLabel('Naziv').fill('Branje')
  await page.getByLabel('Začetek').fill(`${day}T09:00`)
  await page.getByLabel('Konec').fill(`${day}T10:00`)
  await page.getByLabel('Kategorija').selectOption({ label: 'Delo' })
  await page.getByRole('button', { name: 'Potrdi aktivnost' }).click()
  await expect(page.getByText('Branje')).toBeVisible()
  await page.getByRole('button', { name: /Dodaj aktivnost/ }).click()
  await page.getByLabel('Naziv').fill('Pisanje')
  await page.getByLabel('Začetek').fill(`${day}T09:30`)
  await page.getByLabel('Konec').fill(`${day}T10:30`)
  await page.getByLabel('Kategorija').selectOption({ label: 'Delo' })
  await page.getByRole('button', { name: 'Potrdi aktivnost' }).click()
  await expect(page.getByText('Prekrivanje s potrjeno aktivnostjo')).toBeVisible()
  await page.getByRole('button', { name: 'Nadaljuj kljub prekrivanju' }).click()
  await expect(page.getByText('Pisanje')).toBeVisible()
})
