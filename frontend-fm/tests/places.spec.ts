import { test, expect } from '@playwright/test'

test('manages places with manual coordinates and optional geolocation', async ({ page, context }) => {
  const email = `places-${crypto.randomUUID()}@example.com`
  const csrf = await (await page.request.get('/api/auth/csrf')).json()
  await page.request.post('/api/auth/register', { headers: { [csrf.headerName]: csrf.token }, data: { email, password: 'long-password-123' } })
  await page.goto('/')
  await page.getByLabel('E-pošta').fill(email)
  await page.getByLabel('Geslo', { exact: true }).fill('long-password-123')
  await page.getByRole('button', { name: 'Prijava' }).click()
  await page.getByRole('button', { name: 'Lokacije', exact: true }).click()
  await page.getByRole('button', { name: 'Dodaj lokacijo' }).click()
  await page.getByRole('button', { name: 'Shrani lokacijo' }).click()
  await expect(page.getByText('Vnesi ime z največ 120 znaki.')).toBeVisible()
  await page.evaluate(() => { navigator.geolocation.getCurrentPosition = (_success, failure) => failure?.({ code: 1 } as GeolocationPositionError) })
  await page.getByRole('button', { name: 'Uporabi trenutno lokacijo' }).click()
  await expect(page.getByText(/Dovoljenje za lokacijo je zavrnjeno/)).toBeVisible()
  await page.getByLabel('Ime lokacije').fill('Dom')
  await page.getByLabel('Zemljepisna širina').fill('46')
  await page.getByLabel('Zemljepisna dolžina').fill('15')
  await page.getByRole('button', { name: 'Shrani lokacijo' }).click()
  await page.getByRole('button', { name: 'Uredi Dom' }).click()
  await page.getByLabel('Ime lokacije').fill('Pisarna')
  await page.getByRole('button', { name: 'Shrani lokacijo' }).click()
  await page.getByRole('button', { name: 'Izbriši Pisarna' }).click()
  await page.getByRole('button', { name: 'Prekliči', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Uredi Pisarna' })).toBeVisible()
  await page.getByRole('button', { name: 'Izbriši Pisarna' }).click()
  await page.getByRole('button', { name: 'Potrdi brisanje' }).click()
  await expect(page.getByText('Še nimaš shranjenih lokacij.')).toBeVisible()
  await page.reload()
  await context.grantPermissions(['geolocation'])
  await context.setGeolocation({ latitude: 45.5, longitude: 14.5 })
  await page.getByRole('button', { name: 'Lokacije', exact: true }).click()
  await page.getByRole('button', { name: 'Dodaj lokacijo' }).click()
  await page.getByRole('button', { name: 'Uporabi trenutno lokacijo' }).click()
  await expect(page.getByLabel('Zemljepisna širina')).toHaveValue('45.5')
  await expect(page.getByLabel('Zemljepisna dolžina')).toHaveValue('14.5')
})
